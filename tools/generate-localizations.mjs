import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { format } from "prettier";
import * as pluralCategories from "make-plural/pluralCategories";

async function writeGenerated(path, contents) {
  const formatted = await format(contents, {
    filepath: path,
    parser: path.endsWith(".ts") ? "typescript" : "json",
    printWidth: 80,
  });
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== formatted)
      throw new Error(`Stale generated localization: ${path}`);
  } else writeFileSync(path, formatted);
}

const native = fileURLToPath(new URL("../apps/native/", import.meta.url));
const readJson = (path) =>
  JSON.parse(readFileSync(resolve(native, path), "utf8"));
const config = readJson("localization.config.json");
const locales = [...new Set(Object.values(config.storeLocales))].sort();
const source = readJson("src/locales/en.json");
const placeholders = (value) =>
  (value.match(/%\{[^}]+\}/g) ?? []).sort().join("|");

// Validate the whole input before writing any native resources.
const catalogs = locales.map((locale) => {
  const messages = readJson(`src/locales/${locale}.json`);
  if (
    Object.keys(messages).sort().join("\n") !==
    Object.keys(source).sort().join("\n")
  ) {
    throw new Error(`${locale}: catalog keys do not match English`);
  }
  for (const [key, value] of Object.entries(messages)) {
    if (!/^[a-z][a-zA-Z]+\.[a-z][a-zA-Z]+$/.test(key))
      throw new Error(`Invalid semantic key: ${key}`);
    const original = source[key];
    const isPlural = typeof original === "object";
    if (isPlural !== (typeof value === "object" && value !== null))
      throw new Error(`${locale}: wrong message shape for ${key}`);
    if (isPlural) {
      const required = pluralCategories[locale.split("-")[0]].cardinal;
      if (
        Object.keys(value).sort().join("|") !== [...required].sort().join("|")
      )
        throw new Error(`${locale}: incomplete plural categories for ${key}`);
    }
    const variants = isPlural ? Object.values(value) : [value];
    const reference = isPlural ? original.other : original;
    for (const variant of variants) {
      if (
        typeof variant !== "string" ||
        !variant.trim() ||
        placeholders(variant) !== placeholders(reference)
      ) {
        throw new Error(
          `${locale}: invalid translation or placeholders for ${key}`,
        );
      }
    }
  }
  return { locale, messages };
});

const camera = "permissions.cameraUsage";
const photos = "permissions.photosUsage";
const calendar = "permissions.calendarUsage";
mkdirSync(resolve(native, "locales"), { recursive: true });
for (const { locale, messages } of catalogs) {
  const nativeStrings = {
    ios: {
      NSCameraUsageDescription: messages[camera],
      NSPhotoLibraryUsageDescription: messages[photos],
      NSCalendarsUsageDescription: messages[calendar],
      NSCalendarsFullAccessUsageDescription: messages[calendar],
    },
  };
  await writeGenerated(
    resolve(native, `locales/${locale}.json`),
    JSON.stringify(nativeStrings, null, 2) + "\n",
  );
}
const variableName = (locale) =>
  locale.replace(
    /-([A-Za-z]+)/g,
    (_, part) => part[0].toUpperCase() + part.slice(1),
  );
const imports = locales
  .map((locale) => `import ${variableName(locale)} from "./${locale}.json";`)
  .join("\n");
const entries = locales
  .map((locale) => `  ${JSON.stringify(locale)}: ${variableName(locale)},`)
  .join("\n");
await writeGenerated(
  resolve(native, "src/locales/catalogs.ts"),
  `// Generated by pnpm localization:generate from localization.config.json.\n${imports}\n\nexport const catalogs: Record<string, Record<string, string | Record<string, string>>> = {\n${entries}\n};\n`,
);
console.log(
  `Validated and generated ${locales.length} catalogs for ${Object.keys(config.storeLocales).length} App Store locales.`,
);

const notificationCopy = Object.fromEntries(
  catalogs.map(({ locale, messages }) => [
    locale,
    {
      title: messages["digest.title"],
      body: messages["digest.waitingCount"],
    },
  ]),
);
await writeGenerated(
  resolve(native, "convex/model/notificationTranslations.json"),
  JSON.stringify(notificationCopy, null, 2) + "\n",
);

const widgetStrings = Object.fromEntries(
  ["widget.title", "widget.description"].map((key) => [
    source[key],
    {
      extractionState: "manual",
      localizations: Object.fromEntries(
        catalogs.map(({ locale, messages }) => [
          locale,
          {
            stringUnit: { state: "translated", value: messages[key] },
          },
        ]),
      ),
    },
  ]),
);
await writeGenerated(
  resolve(native, "locales/WidgetLocalizations.xcstrings"),
  JSON.stringify(
    { sourceLanguage: "en", strings: widgetStrings, version: "1.0" },
    null,
    2,
  ) + "\n",
);

const parameters = Object.entries(source).map(([key, value]) => {
  const plural = typeof value === "object";
  const text = plural ? value.other : value;
  const names = [
    ...new Set([...text.matchAll(/%\{([^}]+)\}/g)].map((match) => match[1])),
  ];
  const fields = names.map((name) => {
    const param = name === "formattedCount" ? "count" : name;
    return `${param}: ${["count", "saved", "total", "limit"].includes(param) ? "number" : "string"}`;
  });
  return `  ${JSON.stringify(key)}: ${fields.length ? `{ ${fields.join("; ")} }` : "undefined"};`;
});
await writeGenerated(
  resolve(native, "src/locales/message-types.ts"),
  `// Generated by pnpm localization:generate. Do not edit.
export type MessageParams = {
${parameters.join("\n")}
};
export type MessageKey = keyof MessageParams;
export type TextMessageKey = { [K in MessageKey]: MessageParams[K] extends undefined ? K : never }[MessageKey];
export type MessageArgs<K extends MessageKey> = MessageParams[K] extends undefined ? [] : [values: MessageParams[K]];
`,
);
