import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const native = fileURLToPath(new URL("../apps/native/", import.meta.url));
const readJson = (path) =>
  JSON.parse(readFileSync(resolve(native, path), "utf8"));
const config = readJson("localization.config.json");
const locales = [...new Set(Object.values(config.storeLocales))].sort();
const source = readJson("src/locales/en.json");
const placeholders = (value) =>
  (value.match(/%\{[^}]+\}/g) ?? []).sort().join("|");

// Validate the whole input before writing any native resources.
const catalogs = locales.map((locale) => {
  const messages = readJson(`src/locales/${locale}.json`);
  if (
    Object.keys(messages).sort().join("\n") !==
    Object.keys(source).sort().join("\n")
  ) {
    throw new Error(`${locale}: catalog keys do not match English`);
  }
  for (const [key, value] of Object.entries(messages)) {
    if (
      typeof value !== "string" ||
      !value.trim() ||
      placeholders(value) !== placeholders(source[key])
    ) {
      throw new Error(
        `${locale}: invalid translation or placeholders for ${key}`,
      );
    }
  }
  return { locale, messages };
});

const camera =
  "Shelvr uses your camera so you can capture things you want to save for later.";
const photos =
  "Shelvr lets you save photos and screenshots from your library into your hub, and tidy your photo library.";
const calendar =
  "Shelvr adds events to your calendar from things you've saved.";
mkdirSync(resolve(native, "locales"), { recursive: true });
for (const { locale, messages } of catalogs) {
  const nativeStrings = {
    ios: {
      NSCameraUsageDescription: messages[camera],
      NSPhotoLibraryUsageDescription: messages[photos],
      NSCalendarsUsageDescription: messages[calendar],
      NSCalendarsFullAccessUsageDescription: messages[calendar],
    },
  };
  writeFileSync(
    resolve(native, `locales/${locale}.json`),
    JSON.stringify(nativeStrings, null, 2) + "\n",
  );
}
const variableName = (locale) =>
  locale.replace(
    /-([A-Za-z]+)/g,
    (_, part) => part[0].toUpperCase() + part.slice(1),
  );
const imports = locales
  .map((locale) => `import ${variableName(locale)} from "./${locale}.json";`)
  .join("\n");
const entries = locales
  .map((locale) => `  ${JSON.stringify(locale)}: ${variableName(locale)},`)
  .join("\n");
writeFileSync(
  resolve(native, "src/locales/catalogs.ts"),
  `// Generated by pnpm localization:generate from localization.config.json.\n${imports}\n\nexport const catalogs: Record<string, Record<string, string>> = {\n${entries}\n};\n`,
);
console.log(
  `Validated and generated ${locales.length} catalogs for ${Object.keys(config.storeLocales).length} App Store locales.`,
);

const notificationCopy = Object.fromEntries(
  catalogs.map(({ locale, messages }) => [
    locale,
    {
      title: messages["Your weekly shelf"],
      body: messages["Saves waiting for you: %{count}"],
    },
  ]),
);
writeFileSync(
  resolve(native, "convex/model/notificationTranslations.json"),
  JSON.stringify(notificationCopy, null, 2) + "\n",
);

const widgetStrings = Object.fromEntries(
  ["Recent Saves", "Your latest saves, at a glance."].map((key) => [
    key,
    {
      extractionState: "manual",
      localizations: Object.fromEntries(
        catalogs.map(({ locale, messages }) => [
          locale,
          {
            stringUnit: { state: "translated", value: messages[key] },
          },
        ]),
      ),
    },
  ]),
);
writeFileSync(
  resolve(native, "locales/WidgetLocalizations.xcstrings"),
  JSON.stringify(
    { sourceLanguage: "en", strings: widgetStrings, version: "1.0" },
    null,
    2,
  ) + "\n",
);
